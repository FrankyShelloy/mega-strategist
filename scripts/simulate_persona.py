def run_simulation(persona_key: str, output_dir: Path):
    persona = PERSONAS.get(persona_key)
    if not persona:
        print(f"Ошибка: персона {persona_key} не найдена. Доступны: {list(PERSONAS.keys())}", file=sys.stderr)
        return 1

    output_dir.mkdir(parents=True, exist_ok=True)
    today = datetime.now().strftime("%Y-%m-%d")
    filename = output_dir / f"interview_{persona_key}_{today}.md"

    lines = [
        f"# Протокол синтетического интервью: {persona['name']}",
        "",
        "> [!IMPORTANT]",
        "> **ДИСКЛЕЙМЕР [SYNTHETIC-PERSONA]:**",
        "> Данный транскрипт сгенерирован ИИ-агентом в заданной роли для поиска качественных гипотез и ментальных моделей.",
        "> Синтетические ответы НЕ являются доказательством спроса, готовности платить или рыночной доли.",
        "> Все выводы переводятся в статус `[HYP]` и требуют верификации на количественных метриках пилота.",
        "",
        f"**Контекст персоны:** {persona['context']}",
        f"**Основная боль:** {persona['pain']}",
        "",
        "## Стенограмма беседы",
        ""
    ]

    for speaker, text in persona["dialogue"]:
        lines.append(f"**{speaker}:** {text}\n")

    lines.extend([
        "## Качественные инсайты и гипотезы",
        ""
    ])
    for f in persona["findings"]:
        lines.append(f"- [HYP] {f}")

    filename.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Готово: создан протокол интервью {filename.relative_to(ROOT)}")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Симуляция качественных интервью модельных персон")
    parser.add_argument("--persona", choices=list(PERSONAS.keys()), default="organizer_mother",
                        help="ключ персоны для моделирования")
    parser.add_argument("--project", default="projects/demo", help="проект для сохранения артефакта")
    args = parser.parse_args()

    target_dir = ROOT / args.project / "interviews"
    return run_simulation(args.persona, target_dir)


if __name__ == "__main__":
    sys.exit(main())
